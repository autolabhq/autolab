int main(void) {
  size_t case_count = sizeof(cases) / sizeof(cases[0]);
  size_t verified_count = 0;
  size_t failure_count = 0;
  size_t instruction_count = 0;
  size_t result_match_count = 0;
  size_t reused_case_count = 0;
  size_t op_add = 0;
  size_t op_sub = 0;
  size_t op_mul = 0;
  size_t op_neg = 0;
  size_t op_inv = 0;

  for (size_t i = 0; i < case_count; ++i) {
    const case_t *c = &cases[i];
    uint64_t x3 = UINT64_MAX;
    uint64_t y3 = UINT64_MAX;
    int case_failed = 0;
    if (c->reused) {
      reused_case_count += 1;
    }

    for (size_t j = 0; j < c->instruction_count; ++j) {
      const instr_t *instr = &c->instructions[j];
      uint64_t value = 0;
      int ok = 1;
      switch (instr->op) {
        case OP_ADD:
          value = mod_add(instr->a, instr->b, c->p);
          op_add += 1;
          break;
        case OP_SUB:
          value = mod_sub(instr->a, instr->b, c->p);
          op_sub += 1;
          break;
        case OP_MUL:
          value = mod_mul(instr->a, instr->b, c->p);
          op_mul += 1;
          break;
        case OP_NEG:
          value = mod_neg(instr->a, c->p);
          op_neg += 1;
          break;
        case OP_INV:
          value = mod_inv(instr->a, c->p, &ok);
          op_inv += 1;
          break;
      }

      instruction_count += 1;
      if (!ok || value != instr->expected) {
        if (!case_failed) {
          fprintf(
            stderr,
            "case failure source=%s event=%s instr=%zu expected=%" PRIu64 " got=%" PRIu64 "\n",
            c->source_name,
            c->event_key,
            j,
            instr->expected,
            value
          );
        }
        case_failed = 1;
        failure_count += 1;
      }
      if (instr->out_kind == 1) {
        x3 = value;
      } else if (instr->out_kind == 2) {
        y3 = value;
      }
    }

    if (x3 == c->expected_x && y3 == c->expected_y) {
      result_match_count += 1;
    } else {
      if (!case_failed) {
        fprintf(
          stderr,
          "result failure source=%s event=%s expected=(%" PRIu64 ",%" PRIu64 ") got=(%" PRIu64 ",%" PRIu64 ")\n",
          c->source_name,
          c->event_key,
          c->expected_x,
          c->expected_y,
          x3,
          y3
        );
      }
      case_failed = 1;
      failure_count += 1;
    }

    if (!case_failed) {
      verified_count += 1;
    }
  }

  printf(
    "{"
    "\"case_count\":%zu,"
    "\"verified_count\":%zu,"
    "\"failure_count\":%zu,"
    "\"instruction_count\":%zu,"
    "\"result_match_count\":%zu,"
    "\"reused_case_count\":%zu,"
    "\"field_op_counts\":{"
    "\"add\":%zu,"
    "\"sub\":%zu,"
    "\"mul\":%zu,"
    "\"neg\":%zu,"
    "\"inv\":%zu,"
    "\"total\":%zu"
    "}"
    "}\n",
    case_count,
    verified_count,
    failure_count,
    instruction_count,
    result_match_count,
    reused_case_count,
    op_add,
    op_sub,
    op_mul,
    op_neg,
    op_inv,
    instruction_count
  );

  return failure_count == 0 ? 0 : 1;
}
